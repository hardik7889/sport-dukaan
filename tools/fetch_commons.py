import os
import re
import sys
import json
import time
import argparse

import requests
from PIL import Image, ImageStat, ImageFilter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fetch_photos as fp   # noqa: E402

API = 'https://commons.wikimedia.org/w/api.php'
UA = {'User-Agent': 'SportDukaan/1.0 (small shop demo; contact sharmap8853@gmail.com)'}


def log(*a):
    print(*a, flush=True)


def load_map():
    if not os.path.exists(fp.MAP_FILE):
        return {}
    txt = open(fp.MAP_FILE, encoding='utf-8').read()
    body = txt[txt.index('{'):txt.rindex('}') + 1]
    return json.loads(body.replace('\\/', '/'))


def save_map(m):
    lines = ['/* Generated by tools/fetch_photos.py + tools/fetch_commons.py — CC-licensed photos.',
             '   Har entry mein creator + license hai (attribution). */',
             'window.PRODUCT_PHOTOS = ' + json.dumps(m, ensure_ascii=False, indent=2) + ';']
    open(fp.MAP_FILE, 'w', encoding='utf-8').write('\n'.join(lines))


def search(term, session, tries=4):
    for i in range(tries):
        try:
            r = session.get(API, params={
                'action': 'query', 'format': 'json', 'generator': 'search',
                'gsrsearch': 'filetype:bitmap ' + term,
                'gsrnamespace': '6', 'gsrlimit': '20',
                'prop': 'imageinfo',
                'iiprop': 'url|size|mime|extmetadata',
                'iiurlwidth': '1000',
                'iiextmetadatafilter': 'LicenseShortName|Artist',
            }, timeout=30)
            if r.status_code == 200:
                data = r.json()
                pages = (data.get('query') or {}).get('pages') or {}
                return list(pages.values())
        except Exception as e:
            log('   commons error:', e)
        time.sleep(1.5 * (i + 1))
    return []


def pick(pid, spec, session, used):
    queries, must, excl = spec
    must_rx = re.compile(must, re.I) if must else None
    excl_rx = re.compile(excl, re.I) if excl else None

    for term in queries:
        pages = search(term, session)
        log(f'  [{pid}] "{term}" -> {len(pages)} hits')
        cands = []
        for pg in pages:
            ii = (pg.get('imageinfo') or [{}])[0]
            title = (pg.get('title') or '').replace('File:', '').strip()
            url = ii.get('thumburl') or ii.get('url') or ''
            mime = ii.get('mime') or ''
            if not url or mime not in ('image/jpeg', 'image/png', 'image/webp'):
                continue
            if title.lower() in used:
                continue
            if fp.BAD_TITLE.search(title):
                continue
            if must_rx and not must_rx.search(title):
                continue
            if excl_rx and excl_rx.search(title):
                continue
            meta = ii.get('extmetadata') or {}
            lic = (meta.get('LicenseShortName') or {}).get('value') or 'CC-BY'
            artist = (meta.get('Artist') or {}).get('value') or 'Unknown'
            if isinstance(artist, str):
                artist = re.sub('<[^>]+>', '', artist).strip()
            cands.append((pg, ii, title, url, lic, artist))

        for pg, ii, title, url, lic, artist in cands[:10]:
            try:
                resp = session.get(url, timeout=40)
                if resp.status_code != 200:
                    continue
                im = Image.open(__import__('io').BytesIO(resp.content))
                if im.width < 500 or im.height < 380:
                    continue
                b, s = fp.quality(im)
                if b < fp.BRIGHT_MIN or s < fp.SHARP_MIN:
                    log(f'    reject {title[:50]!r} bright={b:.0f} sharp={s:.0f}')
                    continue
                used.add(title.lower())
                return {'id': pid, 'image': im, 'title': title, 'creator': artist,
                        'license': lic, 'license_url': '', 'source': ii.get('descriptionurl') or url,
                        'bright': round(b, 1), 'sharp': round(s, 1)}
            except Exception as e:
                log('    dl error:', e)
        time.sleep(0.6)
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('ids', nargs='*')
    args = ap.parse_args()

    existing = load_map()
    ids = args.ids or [i for i in fp.SPECS if i not in existing]

    session = requests.Session()
    session.headers.update(UA)

    found = {}
    used = set()
    for pid in ids:
        if pid not in fp.SPECS:
            log(f'[{pid}] unknown id, skip')
            continue
        log(f'== {pid} (commons) ==')
        hit = pick(pid, fp.SPECS[pid], session, used)
        if not hit:
            log(f'  [{pid}] COMMONS SE BHI NAHI MILI')
            continue
        out = fp.process(hit.pop('image'))
        path = os.path.join(fp.IMG_DIR, pid + '.webp')
        out.save(path, 'WEBP', quality=84, method=6)
        hit['src'] = 'img/' + pid + '.webp'
        hit['lqip'] = fp.make_lqip(out)
        hit['bytes'] = os.path.getsize(path)
        found[pid] = hit
        log(f'  OK {hit["src"]} {hit["bytes"]//1024}KB bright={hit["bright"]} sharp={hit["sharp"]} '
            f'by {hit["creator"]} ({hit["license"]})')
        time.sleep(0.6)

    existing.update(found)
    save_map(existing)
    log('')
    log(f'=== done: {len(found)}/{len(ids)} new, total {len(existing)} ===')
    missing = [i for i in fp.SPECS if i not in existing]
    if missing:
        log('missing:', ', '.join(missing))


if __name__ == '__main__':
    main()
